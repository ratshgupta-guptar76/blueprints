"""Every requirement in docs/V2_SPEC.md, with the evidence that it holds.

This is the traceability list behind docs/V2_VERIFICATION_PLAN.md. Each
requirement names the checks that test it today on the model:

    checks      (scenario, regex) pairs: a check() in __main__.py whose name matches
    rnd         invariants of random_traffic.py that would break if it did not hold
    mutants     faults in mutants.py that break it and that the pin replay catches
    planned     tests that do not exist yet: module tests on the RTL (L1), chip-level
                RTL tests (L2), gate level (L3), static and formal (L4), silicon (L6)

`python3 -m model.chip_v2.verify matrix` checks every name here against the
real scenarios and mutants and writes docs/V2_REQUIREMENTS_MATRIX.md.

kind:   func    behaviour at the pins, checked by simulation
        inside  behaviour not visible at the pins; needs a test inside the chip
        env     a rule the FPGA must keep; checked by keeping it, and by breaking it
        phys    checked by the physical flow (timing, layout), not by simulation
        perf    a measured number
"""
